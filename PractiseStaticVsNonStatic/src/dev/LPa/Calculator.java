package dev.LPa;

public class Calculator {
    public static int addition(int a,int b){
        return a+b;
    }
    public int substraction(int a,int b){
        return a-b;
    }
    public int multiplication(int a,int b){
        return a*b;
    }
    public static double division(int a,int b){
        return(double) a/b;
    }
}
